/**
 * 资源 ID 的格式 —— 节点 ID 与规则 ID 共用同一条。
 *
 * **抽出来是因为它此前有两份字面相同的副本**（AddNodeModal 与 NewRuleModal），
 * 而这种重复的代价是单向的：改宽一处、另一处没跟上，那一边就多放进一批
 * 后端不认的 id，而症状出现在别的页面上。
 *
 * 格式本身写在 api-contract.md §0.7。它是接口的一部分，不是界面偏好：
 * 这两种 id 都会被拼进 URL 路径、进 DNS 记录的比对键、进证书的 CN，
 * 带 `/` 或 `#` 的 id 在其中任何一处上都会安静地走偏。
 *
 * **后端也挡这一条**（`model.ValidResourceID`，两个入口都拒 1001）。
 * 两道闸不重复：直改路（ops-bot、批量脚本）绕过控制台，而控制台这道
 * 拦得更早 —— 签发 Token 之后人就去跑安装脚本了，那不是代价为零的重来。
 */
export const RESOURCE_ID = /^[a-z0-9][a-z0-9-]{1,39}$/

/** 给人看的那句话。两处共用，免得同一条规矩有两种说法。 */
export const RESOURCE_ID_HINT = '只能用小写字母、数字和连字符，以字母或数字开头，2–40 个字符'
