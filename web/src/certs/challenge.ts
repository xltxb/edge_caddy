/**
 * `challenge` 是「这张证书**怎么来的**」，界面上不直接渲染那个英文值。
 *
 * 抽出来的理由与 `@/nodes/flags` 一样：这是一句**断言**（「这张证书是外部推
 * 进来的」/「这张是主控自己签的」），而写在模板里的断言，只有人盯着截图看的
 * 时候才会被检查一次。
 *
 * ## 为什么「历史」两个字必须说出来
 *
 * ADR-0015 之后主控不再签发证书。库里那些 `dns-01` 是那之前主控自己签的 ——
 * 把它们和新导入的显示成同一种东西，人会以为主控**现在还在签**，于是不去
 * 外部平台续期，而没有任何东西会替他续（契约 §9：到期扫描是唯一的提醒）。
 *
 * ## 字段名不好，而这里是它唯一被解释的地方
 *
 * `challenge` 在 ACME 里指**校验方式**，而 `imported` 恰恰是「没有经过任何
 * 校验」。契约 §9 也记了这一条：留着是因为库里那一列就叫这个名字，改名要动
 * 迁移、契约、前端三处。
 */

const LABEL: Record<string, string> = {
  imported: '外部导入',
  'dns-01': '主控签发（历史）',
}

/**
 * **映射不到就原样显示**，不显示空、也不写成「未知」。
 *
 * 库里那一列是自由文本（内部 CA 的客户端证书就是第三种值）。把认不出的值
 * 吞成空白，等于让一张**来路不明的证书看起来跟别的一样** —— 而「这张证书
 * 哪来的」正是这一列存在的全部理由。
 *
 * 原样显示至少让人看得见有个没见过的值，而空白不会引起任何疑问。
 * （与 `reconnects_1h` 那条同形：**一个假值的危害取决于它引不引起疑问**。）
 */
export function challengeText(v: string): string {
  return LABEL[v] ?? v
}
