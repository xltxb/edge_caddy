/**
 * 节点行上那些**断言**，抽成纯函数。
 *
 * 抽出来不是为了复用 —— 只有一处用它。是为了**能被证伪**：这几句话每一句都是
 * 对现实的断言（「这台机器不接流量了」「这是人关的」），而写在模板里的断言，
 * 只有人盯着截图看的时候才会被检查一次。
 *
 * 后端在 ADR-0014 上撞到过更狠的一层：**一份论证的结论会被测试保护，论证本身
 * 不会。** 它按论证分了两列，而「心跳会冲掉同一列」这个前提没人验 —— 给心跳的
 * SQL 补一句 `drained_at = NULL`（注释写「节点回来了就清掉下线标记」，听起来
 * 完全合理），191 个测试里一条都不红。下面每个函数对应的测试，都是照这个办法
 * 反过来验的：故意改坏，确认真的会红。
 */

import type { EdgeNode } from '@/model'

export interface NodeFlag {
  text: string
  tone: 'muted' | 'warn'
  title?: string
}

/**
 * 行上的旗标。**不含 status** —— 那一格由 VStatusPill 单独占着。
 *
 * `status` 是**观察**（主控连着几个周期没收到心跳），`drainedAt` 是**意图**
 * （人按了下线）。一台节点可以「已下线且在线」，也可以「未下线但离线」；
 * 前者是「我关的」，后者是故障。**合成一格，运维半夜分不清该不该起床**
 * （CONTEXT.md、ADR-0014）。
 */
export function nodeFlags(n: EdgeNode, dnsSyncOk: boolean | null): NodeFlag[] {
  const out: NodeFlag[] = []
  if (n.drainedAt) {
    out.push({ text: '已下线（人为）', tone: 'muted', title: `下线于 ${n.drainedAt}` })
  }
  if (!n.dnsEnabled) {
    // 解析安排没到服务商那边时，「已退出解析」是**常驻的谎** —— 标志位改了，
    // 那台机器照旧在解析里。dnsSyncOk 为 null 表示还没问到，那就不加限定：
    // 宁可少说一句，也不要因为自己没问到就反过来说节点在撒谎。
    out.push({
      text: dnsSyncOk === false ? '已标记退出（解析未变）' : '已退出解析',
      tone: 'warn',
    })
  }
  if (n.drift) out.push({ text: '未收到最近下发', tone: 'warn' })
  /*
   * **判据是 `=== false`，不是 `!n.geoDbOk`。**
   *
   * 三档里只有 `false` 该说话（契约 §6.2）：`true` 是一致，`null` 是主控自己
   * 没有库 —— 那时这套系统压根没在用地域功能，**每台节点标一句红是在报告一个
   * 不存在的问题**，而人两天就学会忽略它，连带着忽略掉真出问题那天的那一条。
   *
   * `!n.geoDbOk` 会把 `null` 一起收进来。两个写法在 diff 里差三个字符，
   * 而它们的区别是「这个功能没在用」和「你的防护全线失效」。
   */
  /*
   * **从没有人给它配过权重** —— 那台机器在解析里不承载任何流量（契约 §2）。
   *
   * 判据是 `weightSet`，**不是 `weight === 0`**：后者分不出
   * 「从没有人过目」和「人看过、给了 0」，而后者是一个**已经做过的决定**。
   * 按权重值判的话，一台人已经决定过的机器会常年挂着这条警告 ——
   * 而一条天天亮着的警告，人两天就学会忽略它。
   *
   * 保存解析页时页面上每个节点都会被写行（含填 0 的），
   * 所以**人只要在那一页上存过一次，这条自己就消失了**。
   *
   * ## 已下线的不标
   *
   * `drainedAt` 是人为下线 —— 那台机器现在本来就不该接流量，
   * 权重不是此刻要处理的事。把它一起标上，等于把一件已经处理好的事
   * 重新摆到人面前。
   *
   * 而 `status: down` 照样标：那是故障不是意图，机器恢复之后
   * 它仍然需要一个权重。
   */
  if (!n.weightSet && !n.drainedAt) {
    out.push({
      text: '未分配权重，不承载流量',
      tone: 'warn',
      title: '这台机器还没有人给它配过权重 —— 它在解析里，但分不到任何流量。去 DNS 调度页给它配一个。',
    })
  }
  if (n.geoDbOk === false) {
    out.push({
      text: 'GeoIP 库未同步',
      tone: 'warn',
      title: '这台节点上的地域规则不生效 —— 库还没到，或者是旧的',
    })
  }
  return out
}

/**
 * 解析开关能不能按。
 *
 * 已下线的节点**两个方向都会被拒**（契约 §4：`2001`）。置灰而不是让人点了
 * 再被拒 —— **一道人人都会撞到的拒绝，说明那个按钮不该能按**。
 *
 * 「关」的方向原先是放行的，理由是「它不会把流量送到一台连不上的机器上」——
 * **那个理由至今成立，它只是漏了一件事**：关这一下会把 `dns_reason` 改写成
 * `manual`，而 `drained_at` 还在。于是节点页说「已下线」、DNS 页说「人手动
 * 关的」，两页各说各的，而**每一句单独看都是对的**。
 *
 * 所以这不是「把约束改严了」。两者在 diff 里长得一样（一条断言反过来了），
 * 但该写进提交的话不同：观测能力变了要写「它为什么**现在**可以更松」，
 * 发现旧约束的代价要写「原来那条**漏了什么**」。这是后一种。
 */
export function canToggleDns(n: EdgeNode): { ok: boolean; reason: string } {
  if (!n.drainedAt) return { ok: true, reason: '' }
  return {
    ok: false,
    reason: n.dnsEnabled
      ? '该节点已被下线，本来就不在解析里'
      : '该节点已被下线，先「重新上线」再恢复解析',
  }
}

/**
 * 能不能删这条记录。**必须先下线**，与 `canToggleDns` 同一个理由置灰：
 * 一道人人都会撞到的拒绝，说明那个按钮不该能按。
 *
 * **但这一条和「危险操作二次确认」是两种东西**，别照那个写措辞。
 *
 * 一台还连着的机器手里有隧道证书。删掉记录之后它会重连、被按证书认出来、
 * 然后在一张不存在的行上写心跳 —— `TouchHeartbeat` 是 UPDATE，影响 0 行，
 * **不报错**。结果是一台连着、在服务、而控制台上看不见的机器。下线会断隧道
 * 并拒绝它重连（ADR-0014），所以下线是这个操作**真正的前提**。
 *
 * 判据（后端 `docs/agents/domain.md`）：
 * **去掉这个检查会产生不一致的状态 → 那是前提；只是「后果严重」→ 那才是确认。**
 * 前提要说「先做那件事」，确认要说「你确定吗」——写反了，人会以为自己在被
 * 劝阻，然后找地方跳过它。
 */
/**
 * 隧道那一格里，**跨时间**的那半句。返回 `null` 表示不必说。
 *
 * 徽标、`online`、心跳年龄全是**瞬时值**。隧道断开到重连只要 1–2 秒，而离线
 * 判定要连续错过 9 秒才翻 down —— **一条每十分钟断一次的隧道，在它们上面全部
 * 是健康的**（契约 §4）。灰度上真发生过，当时唯一的痕迹在 Agent 日志里。
 *
 * 三支各说各的，而**最要紧的是 null 那一支**：
 *
 *   `null`  数不出来 —— 要**明说**。留白会被读成「没问题」，显示 0 更糟。
 *   `0`     不说话 —— 常态，占着地方会稀释掉真正要看的那一行。
 *   `> 0`   说出次数。
 *
 * 这个字段的存在理由就是「在一切看起来正常时指出异常」，而 `0` 恰好是「一切
 * 正常」的样子。**把数不出来渲染成 0，等于让它在自己失效的那一刻，伪装成它
 * 最想否定的那个状态** —— 别的字段退化成 0 只是丢信息，这一个是主动说反话。
 *
 * ## 说「主控记录到几次隧道建立」，不说「断连几次」
 *
 * 契约 §4 的口径是**主控这边的观测**：会话表里记了几次隧道建立。
 * 而同一屏上还有 Agent 日志，那是**那台机器自己的说法** —— 两者在结构上就
 * 不可能对齐：
 *
 * > **一个被 kill 的进程不会记录自己的死亡。**
 *
 * 实测过一次：主控说 3 次，Agent 日志里只有 1 条「隧道断开」，因为另外两次
 * 是它被 SIGTERM 停的，没机会写那行。**主控那份不依赖对方还活着，所以它才是
 * 一手观测。**
 *
 * 措辞写成「断连 N 次」的话，人会拿它去跟下面的 Agent 日志对账 —— 我自己就
 * 这么做了一次，而我是知道内情的那个。**一个错的数字会误导，两个打架的数字
 * 会让人怀疑整页。**
 */
export function reconnectNote(n: EdgeNode): string | null {
  if (n.reconnects1h === null) return '隧道建立次数数不出来（不是 0）'
  if (n.reconnects1h > 0) {
    return `这一小时主控记录到 ${n.reconnects1h} 次隧道建立 —— 上面那几个字段都是此刻的值，看不出这个`
  }
  return null
}

export function canDelete(n: EdgeNode): { ok: boolean; reason: string } {
  if (n.drainedAt) return { ok: true, reason: '' }
  return {
    ok: false,
    reason: '先下线这台节点再删。它现在还连着，删掉记录它会重连并在一张不存在的行上写心跳',
  }
}

/**
 * 「过去一小时拦下了多少」那句话（契约 §4）。
 *
 * ## `null` 必须说出来
 *
 * 跟 `reconnectNote` 同一条：**它要回答的是「此刻在不在被打」，
 * 而 `0` 正是「没被打」的样子** —— 拿 0 当兜底，等于让它在自己失效的
 * 那一刻伪装成它最想否定的那个状态。
 *
 * （同一个 `EdgeNode` 上 `geoDbOk` 的 `null` 恰好相反：那个要闭嘴。
 * 三个 null 挨在一起，处置各不相同。）
 *
 * ## `0` 不等于「没人来打」
 *
 * **处置方式是 `abort`（静默断连）时，被拦的请求不产生任何响应** ——
 * Caddy 按状态码的计数里没有它（后端实测确认）。所以一条黑名单规则
 * 拦得很起劲，这个数照样是 0。
 *
 * 那一句要跟着 0 一起说，否则人会据此以为规则没生效、跑去查规则 ——
 * **而真正该看的是那条路由的处置方式**。
 *
 * ## 窗口在主控的内存里
 *
 * 重启后从 0 重新攒（与 `cpu_series` 同一条路）。不说清的话，
 * 一个刚重启完的主控看起来像刚过了一段太平日子。
 */
export function blockedNote(n: EdgeNode): string | null {
  if (n.blocked1h === null) {
    return '拦截数还没有 —— 这台刚接入，或者主控重启后还没攒够两次心跳'
  }
  if (n.blocked1h === 0) {
    return '这一小时没有被拦下的请求。处置方式选「静默断连」的路由数不进来 —— 那种拦截不产生响应'
  }
  return `这一小时拦下 ${n.blocked1h} 个请求（限流 429 与 403 / 404；主控重启后重新攒）`
}
