-- 记下「上一次为这张证书的到期发过告警」是什么时候。
--
-- **它必须落库，不能只存在内存里。**
--
-- 到期扫描每天跑一次，而主控重启是例行操作（今天一晚上部署了六七次）。
-- 存在内存里的话，每重启一次就会为同一张证书重报一次警——
-- **一个重启就重复报警的系统，会教会运维忽略那一类告警**，
-- 而下次真有证书要过期时他们照旧会忽略。
--
-- 这跟 health 那边「库里已经是 down 的不再报离线」是同一条理由，
-- 同一份代码里已经写过一遍。
ALTER TABLE certs ADD COLUMN expiry_alerted_at TIMESTAMPTZ;
